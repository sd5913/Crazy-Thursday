// Validate the single food content source and generate the English runtime data.
// food-assets/ holds every food image, the bilingual catalogue and the category
// definitions. Nothing under src/ or www/ is hand-edited: build.mjs exports the
// PNGs into www/assets/food and copies the runtime data into www/.
// Run with: npm run food:sync (also run automatically by npm run build).
import { readFile, writeFile, stat, readdir } from 'node:fs/promises';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const source = join(root, 'food-assets');
const art = join(source, 'png');

const catalogue = JSON.parse(await readFile(join(source, 'catalogue.json'), 'utf8'));
const categories = catalogue.categories;
const categoryNames = new Set(Object.keys(categories));
const seen = new Set();
const expected = new Set();

for (const it of catalogue.items) {
  if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(it.id)) throw new Error(`bad id: ${it.id}`);
  if (seen.has(it.id)) throw new Error(`duplicate id: ${it.id}`);
  seen.add(it.id);
  if (!categoryNames.has(it.category)) throw new Error(`unknown category: ${it.id}`);
  if (typeof it.eatable !== 'boolean') throw new Error(`unresolved eatable: ${it.id}`);
  if (it.status !== 'ready') throw new Error(`not ready: ${it.id}`);
  if (!it.name || !it.name_zh || !it.line || !it.line_zh) throw new Error(`missing EN/ZH text: ${it.id}`);
  const image = `png/${it.category}/${it.id}.png`;
  if (it.image !== image) throw new Error(`bad image path: ${it.id} expected ${image}, got ${it.image}`);
  if (!(await stat(join(source, it.image))).size) throw new Error(`empty image: ${it.image}`);
  expected.add(`${it.category}/${it.id}.png`);
}

// The category folders are the physical form of catalogue.categories. Reject
// stray folders, non-PNG files and orphan images so the two cannot drift apart.
for (const entry of await readdir(art, { withFileTypes: true })) {
  if (!entry.isDirectory() || !categoryNames.has(entry.name)) throw new Error(`unexpected entry in png/: ${entry.name}`);
  for (const file of await readdir(join(art, entry.name))) {
    if (!file.endsWith('.png')) throw new Error(`unexpected file: png/${entry.name}/${file}`);
    if (!expected.has(`${entry.name}/${file}`)) throw new Error(`orphan image: png/${entry.name}/${file}`);
  }
}
for (const [name, def] of Object.entries(categories)) {
  const count = catalogue.items.filter((it) => it.category === name).length;
  if (def.path && def.path !== `png/${name}/`) throw new Error(`bad category path: ${name}`);
  if (def.count !== undefined && def.count !== count) throw new Error(`category count mismatch: ${name} says ${def.count}, has ${count}`);
  def.resolvedCount = count;
}

// Keep both languages in the shipped runtime data: name/line stay English for
// the current UI, and the *_zh fields are ready for a future global switch.
// Field names match food-assets/catalogue.json one-to-one for easy extraction.
const items = catalogue.items.map((it) => ({
  id: it.id,
  name: it.name,
  name_zh: it.name_zh,
  eatable: it.eatable,
  category: it.category,
  line: it.line,
  line_zh: it.line_zh,
  image: `assets/food/${it.id}.png`,
}));

const banner = [
  '// Generated by scripts/sync-food-assets.mjs from food-assets/catalogue.json.',
  '// Do not edit by hand: food-assets/ is the only content source (bilingual).',
  '// Bilingual runtime data; build.mjs copies it to www/. Gameplay currently',
  '// reads name/line (English). Use foodText(item, language) for a locale switch.',
  '',
].join('\n');
const helpers = `
// Language codes follow the debug UI convention ('en' / 'zh').
export const FOOD_LOCALES = ['en', 'zh'];

// One extraction point for a future global language switch. Unknown or
// unsupported languages fall back to English, so the game never shows blanks.
export function foodText(item, language = 'en') {
  if (language === 'zh') return { name: item.name_zh, line: item.line_zh };
  return { name: item.name, line: item.line };
}
`;
const runtime = join(root, 'src', 'food-catalogue.js');
const output = `${banner}export const FOOD_ITEMS = ${JSON.stringify(items, null, 2)};\n${helpers}`;
// Leave mtimes alone when nothing changed, so incremental builds stay fast.
if ((await readFile(runtime, 'utf8').catch(() => '')) !== output) await writeFile(runtime, output, 'utf8');

// build.mjs uses this to export the single set of images into the web bundle.
export const FOOD_ART = catalogue.items.map((it) => ({
  from: join(source, it.image),
  to: `${it.id}.png`,
}));

const counts = [...categoryNames].map((k) => `${k}=${categories[k].resolvedCount}`).join(', ');
console.log(`Validated ${items.length} food items (${counts}) in food-assets/`);
